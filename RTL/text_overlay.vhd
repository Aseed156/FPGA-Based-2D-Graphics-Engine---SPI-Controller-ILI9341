        variable font_col : integer;
        variable font_row : integer;
        variable rom_base : integer;
        variable bit_val  : std_logic;
    begin
        isSet   <= '0';
        bit_val := '0';
 
        px := to_integer(checkX);
        py := to_integer(checkY);
 
        -- ── Line 1: "Aseed Faisal" ──────────────────────────────────────────
