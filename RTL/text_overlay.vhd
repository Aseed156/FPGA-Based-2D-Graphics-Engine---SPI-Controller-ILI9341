              py >= L2_Y and py < L2_Y + GLYPH_H then
 
            char_idx := (px - L2_X) / (CHAR_W * SCALE);  -- 0..5
            font_col := ((px - L2_X) / SCALE) mod CHAR_W; -- 0..7
            font_row := (py - L2_Y) / SCALE;              -- 0..7
 
            -- Line 2 chars start at ROM index L1_CHARS * CHAR_H = 40
            rom_base := L1_CHARS * CHAR_H + char_idx * CHAR_H + font_row;
            bit_val  := FONT_ROM(rom_base)(7 - font_col);
 
        end if;
 
        isSet <= bit_val;
    end process;
 
