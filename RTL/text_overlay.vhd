           py >= L1_Y and py < L1_Y + GLYPH_H then
 
            char_idx := (px - L1_X) / (CHAR_W * SCALE); 
            font_col := ((px - L1_X) / SCALE) mod CHAR_W; 
            font_row := (py - L1_Y) / SCALE;             
 
            -- Line 1 chars start at ROM index 0
            rom_base := char_idx * CHAR_H + font_row;
            bit_val  := FONT_ROM(rom_base)(7 - font_col);
 
        -- ── Line 2: "Fa23-BCE-022" ─────────────────────────────────────────
